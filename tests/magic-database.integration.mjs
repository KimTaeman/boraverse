import assert from "node:assert/strict";
import { randomUUID, randomBytes } from "node:crypto";
import { readFile } from "node:fs/promises";
import pg from "pg";
import { listLetters, performMagic } from "../src/lib/magic/store.ts";
if (process.env.OCEAN_WRITE_ENABLED !== "false" || process.env.MAGIC_WRITE_ENABLED !== "false") throw new Error("Both public write switches must be explicitly disabled.");
const url = new URL(process.env.DATABASE_URL);
for (const key of ["sslmode", "sslcert", "sslkey", "sslrootcert"]) url.searchParams.delete(key);
const ca = process.env.DATABASE_CA_CERT || await readFile(process.env.DATABASE_CA_CERT_PATH, "utf8");
const client = new pg.Client({ connectionString: url.toString(), ssl: { ca, rejectUnauthorized: true }, connectionTimeoutMillis: 10000 });
let transaction = false;
const hash = () => randomBytes(32).toString("hex");
const ownerHash = hash(), readerHash = hash();
const input = { action: "submit", visitorToken: randomUUID(), requestId: randomUUID(), kind: "bangtan", title: "Rollback test", text: "An original test letter that must never remain.", consent: true };
try {
  await client.connect();
  assert.equal((await client.query("select to_regclass('app_private.magic_messages') is null as absent")).rows[0].absent, true, "This rollback-only migration test requires the new schema not to be applied yet.");
  await client.query("BEGIN"); transaction = true;
  await client.query("set local lock_timeout='5s'"); await client.query("set local statement_timeout='10s'");
  await client.query(await readFile(new URL("../supabase/migrations/20261116133329_magic_shop.sql", import.meta.url), "utf8"));
  await client.query("grant ocean_app to current_user");
  await client.query("set local role ocean_app");
  const first = await performMagic(client, ownerHash, input);
  assert.equal(first.status, "submitted"); assert.equal(first.reviewStatus, "pending");
  assert.equal((await performMagic(client, ownerHash, input)).submissionId, first.submissionId);
  assert.equal((await listLetters(client)).items.length, 0, "Pending content must not be in the feed.");
  await client.query("savepoint denied_publish");
  await assert.rejects(client.query("update app_private.magic_messages set status='published',published_at=now() where id=$1", [first.submissionId]), /row-level security/);
  await client.query("rollback to savepoint denied_publish");
  await client.query("select set_config('app.magic_visitor',$1,true)", [readerHash]);
  assert.equal((await client.query("select id from app_private.magic_messages where id=$1", [first.submissionId])).rows.length, 0, "Another visitor cannot read the pending row.");
  await client.query("reset role");
  await client.query("update app_private.magic_messages set status='published',published_at=now() where id=$1", [first.submissionId]);
  const armyId = randomUUID();
  await client.query("insert into app_private.magic_messages(id,request_id,kind,title,body,author_hash,status,published_at) values($1,$2,'army','Kindness','A kind test message.',$3,'published',now())", [armyId, randomUUID(), ownerHash]);
  await client.query("set local role ocean_app");
  const feed = await listLetters(client); assert.equal(feed.items.length, 1);
  assert.deepEqual(Object.keys(feed.items[0]).sort(), ["id", "reactions", "text", "title"]);
  const react = { action: "react", visitorToken: randomUUID(), requestId: randomUUID(), messageId: first.submissionId, active: true };
  const agreement = await performMagic(client, readerHash, react); assert.equal(agreement.reactions, 1);
  assert.equal((await performMagic(client, readerHash, react)).reactions, 1);
  const removed = await performMagic(client, readerHash, { ...react, requestId: randomUUID(), active: false }); assert.equal(removed.reactions, 0);
  assert.equal((await performMagic(client, readerHash, react)).active, false, "An old retry cannot reapply an earlier reaction after a newer removal.");
  const draw = { action: "draw", visitorToken: randomUUID() };
  assert.equal((await performMagic(client, readerHash, draw)).message.id, armyId);
  assert.equal((await performMagic(client, readerHash, { ...draw, previousId: armyId })).message, null);
  assert.equal((await performMagic(client, ownerHash, draw)).message, null, "Do not draw the author's own message.");
  const conflict = await performMagic(client, readerHash, { ...input, visitorToken: randomUUID() }); assert.equal(conflict.status, "conflict");
  const denied = await performMagic(client, readerHash, { action: "remove", requestId: randomUUID(), visitorToken: randomUUID(), messageId: first.submissionId });
  assert.equal(denied.status, "not_found");
  const withdraw = await performMagic(client, ownerHash, { action: "remove", requestId: randomUUID(), visitorToken: input.visitorToken, messageId: first.submissionId }); assert.equal(withdraw.status, "withdrawn");
  assert.equal((await listLetters(client)).items.length, 0);
  await client.query("reset role");
  const grants = await client.query("select has_table_privilege('anon','app_private.magic_messages','SELECT') or has_table_privilege('authenticated','app_private.magic_messages','INSERT') as exposed");
  assert.equal(grants.rows[0].exposed, false);
  await client.query("ROLLBACK"); transaction = false;
  assert.equal((await client.query("select to_regclass('app_private.magic_messages') is null as absent")).rows[0].absent, true);
  console.log("Magic Shop migration/RLS, pending-only submission, owner-only publication, published-only feed, retry-safe agreement/removal, random-message eligibility and withdrawal passed; migration rolled back.");
} finally { if (transaction) await client.query("ROLLBACK").catch(() => {}); await client.end().catch(() => {}); }
